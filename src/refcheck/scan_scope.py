"""Which files and directories a scan reads."""

from dataclasses import dataclass
from fnmatch import fnmatch
from itertools import chain
from pathlib import Path

EXCLUDED_DIRECTORY_NAMES = frozenset(
    {
        '.git',
        'node_modules',
        '.venv',
        'site',
        '__pycache__',
        '.cache',
        # Tool caches record what a path *was* on the last run, same as the
        # append-only logs excluded below. .pytest_cache/v/cache/nodeids holds a
        # node ID per collected test, so renaming a test package reported twenty
        # misses against a file regenerated by the next pytest run.
        '.pytest_cache',
        '.ruff_cache',
        '.mypy_cache',
    }
)

EXCLUDED_PATTERNS = (
    '*.pyc',
    'site/**',
    # Append-only event logs record what a path *was*, not what should
    # exist. A 197 MB log naming every file a hook had ever checked reported
    # nine misses for one query, all of them history.
    '*.jsonl',
    # Same reasoning: a run transcript names what existed when it ran. A
    # gitignored test log reported the pre-rename name of a tool that had
    # just been renamed everywhere it is actually referenced.
    '*.log',
    # A changelog is that same thing written deliberately: an entry naming
    # cli/Makefile is correct precisely because that is where the file was
    # when it shipped, and rewriting history to match the current tree would
    # be the bug. Replaying twenty-two real renames across a machine, seven
    # of the hits were changelog entries — the largest single source of
    # noise in the run.
    'CHANGELOG.md',
    # A backup is a copy of what a file said when it was taken, the same
    # record a changelog is, so an old name in one was correct on the day
    # it was written.
    '*.bak',
    '*.backup',
    '*.backup.*',
    '*.orig',
    # coverage.py's outputs list every file measured on the last run, so a
    # renamed module stays in them until the next run rewrites them. A hook
    # writing .coverage.json on every commit failed --moves on each Python
    # rename, and that report was the only hit.
    '.coverage',
    '.coverage.*',
    'coverage.json',
    'coverage.xml',
    'coverage.lcov',
    'htmlcov/**',
    '**/htmlcov/**',
)

# A fixtures directory holds recorded data, not references. A captured tool
# output — a file listing, a coverage report — names every file that existed
# when it was taken, so one commit deleting a subsystem made a single such
# file 219 of the 280 hits in one run, burying the four that were real.
# Nobody would hand-edit one either; the fix is to re-run the tool that
# wrote it. `--test-mode` scans them anyway.
RECORDED_FIXTURE_PATTERNS = (
    'fixtures/**',
    '**/fixtures/**',
    'testdata/**',
    '**/testdata/**',
    'docs/archive/**',
)


@dataclass(frozen=True)
class BuiltinLayer:
    """One built-in list of exclusions, under the name `config show` prints it by.

    `rule` describes a layer decided by a predicate rather than a list, which
    `ScanScope` applies itself.
    """

    name: str
    directories: frozenset[str] = frozenset()
    patterns: tuple[str, ...] = ()
    rule: str | None = None
    read_under_test_mode: bool = False


BUILTIN_LAYERS = (
    BuiltinLayer('directory names', directories=EXCLUDED_DIRECTORY_NAMES),
    BuiltinLayer('build output', rule='a target directory beside a Cargo.toml'),
    BuiltinLayer('patterns', patterns=EXCLUDED_PATTERNS),
    BuiltinLayer('recorded fixtures', patterns=RECORDED_FIXTURE_PATTERNS, read_under_test_mode=True),
)


def builtin_layers(test_mode: bool) -> list[BuiltinLayer]:
    """The built-in layers a scan applies, less the ones --test-mode reads."""
    return [layer for layer in BUILTIN_LAYERS if not (test_mode and layer.read_under_test_mode)]


def is_cargo_build_dir(directory: Path) -> bool:
    """Whether a directory is Cargo's build output, which sits beside the Cargo.toml that owns it.

    Its dependency files and fingerprints name every source file as of the last
    build. Deleting one module from a Rust workspace failed --moves on two `.d`
    files under crates/target and on nothing else. A `target` with no Cargo.toml
    beside it is matched by nothing here, so a source directory of that name is
    still read.
    """
    return directory.name == 'target' and (directory.parent / 'Cargo.toml').is_file()


class ScanScope:
    """The exclusions one tree is scanned under, asked of repo-relative paths."""

    BINARY_SUFFIXES = {'.pyc', '.so', '.o', '.a', '.dylib'}

    def __init__(self, root_dir: Path, exclude_dirs: set[str] | frozenset[str], exclude_patterns: list[str]):
        self.root_dir = root_dir
        self.exclude_dirs = exclude_dirs
        self.exclude_patterns = exclude_patterns

    @classmethod
    def for_tree(cls, root_dir: Path, repo_patterns: list[str], test_mode: bool = False) -> 'ScanScope':
        """The built-in layers a run applies, then the patterns the repo's own config declares.

        The built-ins hold what is true of any repository. Which of a repo's
        own directories hold generated output is a fact only that repo knows.
        """
        layers = builtin_layers(test_mode)
        directories = frozenset(chain.from_iterable(layer.directories for layer in layers))
        patterns = [*chain.from_iterable(layer.patterns for layer in layers), *repo_patterns]
        return cls(root_dir, directories, patterns)

    def should_skip_directory(self, rel_path: Path) -> bool:
        """Whether a whole subtree is outside what the scan reads.

        Asked during the descent rather than after it, so an excluded
        directory is never entered. That is what keeps it out of the coverage
        claim as well as out of the results: a directory the scan was
        configured to skip is outside what the run promised to read, so a
        refusal inside it is not a shortfall and must not fail the run.

        A subtree pattern is matched against the path with a trailing slash.
        `build/**` describes what is under `build`, and without the slash the
        directory itself matches nothing while everything inside it matches.
        """
        if any(part in self.exclude_dirs for part in rel_path.parts):
            return True
        if is_cargo_build_dir(self.root_dir / rel_path):
            return True
        return any(fnmatch(f'{rel_path.as_posix()}/', pattern) for pattern in self.exclude_patterns)

    def should_skip_file(self, rel_path: Path) -> bool:
        """Whether a file is outside what the scan reads, by its place, its name or its content."""
        if any(part in self.exclude_dirs for part in rel_path.parts):
            return True

        if any(is_cargo_build_dir(self.root_dir / parent) for parent in rel_path.parents if parent.name == 'target'):
            return True

        if self._matches_exclusion(rel_path):
            return True

        if rel_path.suffix in self.BINARY_SUFFIXES:
            return True

        # Callers pass a repo-relative path, so the read is anchored at the root
        # rather than at the working directory. Scanning a repo that is not the
        # one you are standing in opened the wrong path, got OSError, and read
        # "not binary" — which let a 30 MB Go executable through as text.
        return self._holds_binary_content(self.root_dir / rel_path)

    def _matches_exclusion(self, rel_path: Path) -> bool:
        """Match an exclusion pattern against a repo-relative path.

        Two matchers, because the patterns are two kinds. `*.log` and
        `CHANGELOG.md` name a file wherever it sits, which is Path.match's
        right-anchored semantics. `dir/**` names a subtree — and Path.match
        reads `**` as one component, so alone it would exclude
        `build/reports/top.json` while scanning `build/reports/a/b.json`
        right beside it. fnmatch over the posix string is anchored at the root and
        lets `*` cross separators, which is what a subtree pattern means.
        """
        posix = rel_path.as_posix()
        return any(rel_path.match(pattern) or fnmatch(posix, pattern) for pattern in self.exclude_patterns)

    @staticmethod
    def _holds_binary_content(file_path: Path) -> bool:
        """True if the first block holds a NUL byte — the heuristic git uses.

        A suffix list never keeps up. A multi-gigabyte SQLite database with no
        matching extension was read as text and pattern-matched, producing 29 of
        the 31 hits for one `--pattern` query. Every false positive spends the
        credibility this tool needs to get used at all.
        """
        try:
            with file_path.open('rb') as handle:
                return b'\0' in handle.read(8192)
        except OSError:
            return False
